create table if not exists public.bs_grade_race_events (
  id bigint generated by default as identity primary key,
  start_date date not null,
  end_date date not null,
  course_code smallint not null check (course_code between 1 and 24),
  grade text not null check (grade in ('SG','PG1','G1','G2','G3')),
  title text not null,
  source text not null default 'boatrace_official',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint bs_grade_race_events_dates check (end_date >= start_date),
  constraint bs_grade_race_events_unique unique (start_date, course_code, grade, title)
);

alter table public.bs_grade_race_events enable row level security;
create index if not exists bs_grade_race_events_date_idx on public.bs_grade_race_events (start_date, end_date);
create index if not exists bs_grade_race_events_course_idx on public.bs_grade_race_events (course_code, start_date);

