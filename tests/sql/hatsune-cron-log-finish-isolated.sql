\set ON_ERROR_STOP on
BEGIN;
CREATE SCHEMA hatsune_finish_test;
CREATE TABLE hatsune_finish_test.hatsune_news_cron_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status text NOT NULL,
  inserted_count integer NOT NULL DEFAULT 0,
  finished_at timestamptz
);
INSERT INTO hatsune_finish_test.hatsune_news_cron_runs(id,status) VALUES (1,'running'),(2,'running');
CREATE ROLE hatsune_finish_denied NOLOGIN;
REVOKE ALL ON SCHEMA hatsune_finish_test FROM PUBLIC;
GRANT USAGE ON SCHEMA hatsune_finish_test TO hatsune_finish_denied;
GRANT SELECT ON hatsune_finish_test.hatsune_news_cron_runs TO hatsune_finish_denied;
-- PostgreSQL UPDATE ... RETURNING is analogous to PostgREST update().select().
UPDATE hatsune_finish_test.hatsune_news_cron_runs
 SET status='partial',inserted_count=2,finished_at=now()
 WHERE id=1 RETURNING id;
DO $$
BEGIN
 IF (SELECT status FROM hatsune_finish_test.hatsune_news_cron_runs WHERE id=1)<>'partial'
 OR (SELECT inserted_count FROM hatsune_finish_test.hatsune_news_cron_runs WHERE id=1)<>2
 OR (SELECT status FROM hatsune_finish_test.hatsune_news_cron_runs WHERE id=2)<>'running'
 THEN RAISE EXCEPTION 'completion update failed'; END IF;
END $$;
CREATE TEMP TABLE zero_match_probe (count_rows bigint);
WITH updated AS (
 UPDATE hatsune_finish_test.hatsune_news_cron_runs
 SET status='success' WHERE id=999 RETURNING id
) INSERT INTO zero_match_probe SELECT count(*) FROM updated;
DO $$
BEGIN
 IF (SELECT count_rows FROM zero_match_probe)<>0 THEN
  RAISE EXCEPTION 'missing row should not be updated';
 END IF;
END $$;
-- Test actual database permission rejection in a catchable subtransaction.
DO $$
BEGIN
 BEGIN
  EXECUTE 'SET LOCAL ROLE hatsune_finish_denied';
  UPDATE hatsune_finish_test.hatsune_news_cron_runs SET status='success' WHERE id=2;
  RAISE EXCEPTION 'denied role unexpectedly updated';
 EXCEPTION WHEN insufficient_privilege THEN
  RAISE NOTICE 'PASS: denied role cannot update';
 END;
END $$;
ROLLBACK;
