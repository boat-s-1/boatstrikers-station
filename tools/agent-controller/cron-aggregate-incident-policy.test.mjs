import test from 'node:test';
import assert from 'node:assert/strict';
import {evaluateCronAggregateIncident as assess} from './cron-aggregate-incident-policy.mjs';
const base={attemptAt:'2026-11-17T09:00:00Z',referenceAt:'2026-11-17T09:05:00Z'};
const run=(changes={})=>assess({...base,outcome:'timeout',...changes});
test('timeout proposes operator alert',()=>assert.equal(run().alert_proposal,'operator_review_required'));
test('connection error proposes alert',()=>assert.equal(run({outcome:'connection_error'}).alert_proposal,'operator_review_required'));
test('permission denied proposes alert',()=>assert.equal(run({outcome:'permission_denied'}).alert_proposal,'operator_review_required'));
test('invalid result proposes alert',()=>assert.equal(run({outcome:'invalid_result'}).alert_proposal,'operator_review_required'));
test('policy hold proposes alert',()=>assert.equal(run({outcome:'policy_hold'}).alert_proposal,'operator_review_required'));
test('success proposes no alert',()=>assert.equal(run({outcome:'success'}).alert_proposal,'none'));
test('success has no alert reason',()=>assert.equal(run({outcome:'success'}).alert_reason,null));
test('record has no secrets',()=>assert.equal(run().record.contains_secrets,false));
test('record includes outcome',()=>assert.equal(run().record.outcome,'timeout'));
test('no actual persistence',()=>assert.equal(run().actual_record_persisted,false));
test('no actual notification',()=>assert.equal(run().actual_alert_sent,false));
test('no automatic retry',()=>assert.equal(run().automatic_retry_allowed,false));
test('no republish',()=>assert.equal(run().automatic_republish_allowed,false));
test('no provider API access',()=>assert.equal(run().provider_api_accessed,false));
test('no production mutation',()=>assert.equal(run().production_mutation_performed,false));
test('cooldown suppresses repeat alert',()=>assert.equal(run({previousAlertAt:'2026-11-17T08:30:00Z'}).alert_proposal,'none'));
test('cooldown flag records suppression',()=>assert.equal(run({previousAlertAt:'2026-11-17T08:30:00Z'}).alert_suppressed_by_cooldown,true));
test('alert allowed at cooldown boundary',()=>assert.equal(run({previousAlertAt:'2026-11-17T08:05:00Z'}).alert_proposal,'operator_review_required'));
test('invalid outcome rejected',()=>assert.throws(()=>run({outcome:'replayed'}),/invalid outcome/));
test('invalid timestamp rejected',()=>assert.throws(()=>run({attemptAt:'yesterday'}),/invalid attemptAt/));
test('future attempt rejected',()=>assert.throws(()=>run({attemptAt:'2026-11-17T09:06:00Z'}),/attempt in future/));
test('future alert rejected',()=>assert.throws(()=>run({previousAlertAt:'2026-11-17T09:06:00Z'}),/alert in future/));
test('short cooldown rejected',()=>assert.throws(()=>run({alertCooldownMs:1000}),/invalid alertCooldownMs/));
test('invalid cooldown rejected',()=>assert.throws(()=>run({alertCooldownMs:-1}),/invalid alertCooldownMs/));
