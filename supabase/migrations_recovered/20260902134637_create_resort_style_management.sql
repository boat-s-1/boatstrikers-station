
create extension if not exists pgcrypto;

create table if not exists public.resort_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.resort_stores (
  id smallint generated by default as identity primary key,
  code text not null unique check (code ~ '^[a-z0-9-]+$'),
  name text not null unique,
  display_order smallint not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.resort_therapists (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name text not null,
  age smallint check (age between 18 and 99),
  height smallint check (height between 100 and 220),
  profile_text text not null default '',
  manager_comment text not null default '',
  nomination_fee integer not null default 0 check (nomination_fee >= 0),
  image_path text,
  x_url text,
  instagram_url text,
  bluesky_url text,
  is_published boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.resort_therapist_stores (
  therapist_id uuid not null references public.resort_therapists(id) on delete cascade,
  store_id smallint not null references public.resort_stores(id) on delete cascade,
  primary key (therapist_id, store_id)
);

create table if not exists public.resort_schedules (
  id uuid primary key default gen_random_uuid(),
  therapist_id uuid not null references public.resort_therapists(id) on delete cascade,
  store_id smallint not null references public.resort_stores(id) on delete restrict,
  work_date date not null,
  start_time time,
  end_time time,
  note text not null default '',
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (therapist_id, work_date),
  check (end_time is null or start_time is null or end_time > start_time)
);

create or replace function public.resort_set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists resort_therapists_updated_at on public.resort_therapists;
create trigger resort_therapists_updated_at
before update on public.resort_therapists
for each row execute function public.resort_set_updated_at();

drop trigger if exists resort_schedules_updated_at on public.resort_schedules;
create trigger resort_schedules_updated_at
before update on public.resort_schedules
for each row execute function public.resort_set_updated_at();

