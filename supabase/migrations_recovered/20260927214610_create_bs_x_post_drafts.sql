create table if not exists public.bs_x_post_drafts (
  id bigint generated by default as identity primary key,
  post_date date not null,
  account_code text not null check (account_code in ('official','ichika','hatsune','kiina')),
  category text not null check (category in ('prediction','result','news','data_lab','character_chat','beginner','announcement')),
  title text,
  body text not null default '',
  status text not null default 'draft' check (status in ('draft','review','ready','posted')),
  scheduled_at timestamptz,
  posted_at timestamptz,
  source_kind text,
  source_refs jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists bs_x_post_drafts_post_date_idx on public.bs_x_post_drafts(post_date, scheduled_at);
create index if not exists bs_x_post_drafts_account_status_idx on public.bs_x_post_drafts(account_code, status);
alter table public.bs_x_post_drafts enable row level security;
comment on table public.bs_x_post_drafts is 'Review-first X post drafts for BoatStrikers official and character accounts. Server/admin access only in Phase 1.';