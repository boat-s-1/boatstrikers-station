import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const sql=readFileSync(new URL('./sql/hatsune-cron-aggregate-readonly.sql',import.meta.url),'utf8');
const executable=sql.split('\n').filter(line=>!line.trim().startsWith('--')).join('\n');
test('only SELECT query',()=>assert.match(executable.trim(),/^WITH bounds AS \(/i));
test('no insert',()=>assert.doesNotMatch(executable,/\bINSERT\b/i));
test('no update',()=>assert.doesNotMatch(executable,/\bUPDATE\b/i));
test('no delete',()=>assert.doesNotMatch(executable,/\bDELETE\b/i));
test('no create or alter',()=>assert.doesNotMatch(executable,/\b(CREATE|ALTER|DROP|TRUNCATE)\b/i));
test('no function execution',()=>assert.doesNotMatch(executable,/\bCALL\b/i));
test('bounded to 21 days',()=>assert.match(executable,/interval '21 days'/));
test('excludes recent three minutes',()=>assert.match(executable,/interval '3 minutes'/));
test('article window two minutes',()=>assert.match(executable,/interval '2 minutes'/));
test('filters pipeline job',()=>assert.match(executable,/r\.job_name = 'pipeline'/));
test('returns observation timestamp',()=>assert.match(executable,/AS observed_at/));
test('returns window start',()=>assert.match(executable,/AS window_start/));
test('returns window end',()=>assert.match(executable,/AS window_end/));
test('returns total run count',()=>assert.match(executable,/AS runs_total/));
test('returns unfinished count',()=>assert.match(executable,/AS running_without_finish/));
test('returns partial count',()=>assert.match(executable,/AS partial_runs/));
test('returns article windows',()=>assert.match(executable,/AS windows_with_articles/));
test('returns temporal article matches',()=>assert.match(executable,/AS temporal_article_matches/));
test('does not select article body',()=>assert.doesNotMatch(executable,/\b(n\.body|n\.content|n\.title)\b/i));
test('final output does not expose raw identifiers',()=>{const finalSelect=executable.slice(executable.lastIndexOf('SELECT to_char'));assert.doesNotMatch(finalSelect,/\\b(r\\.id|n\\.id|p\\.id\\s+AS)\\b/i)});

test('bounded articles materialized once',()=>assert.match(executable,/bounded_articles AS MATERIALIZED/));
test('run windows materialized',()=>assert.match(executable,/run_windows AS MATERIALIZED/));
test('article scan bounded by window',()=>assert.match(executable,/n\.created_at >= b\.window_start/));
