export function getStadiumBasicGuide(value) {
  const raw = String(value ?? "").trim().toLowerCase();
  const code = Number(raw);
  return STADIUM_BASIC_GUIDES.find((item) =>
    item.slug === raw || item.courseCode === code || String(item.courseCode).padStart(2, "0") === raw
  ) || null;
}