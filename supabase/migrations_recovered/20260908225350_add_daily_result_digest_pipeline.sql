create unique index if not exists hatsune_news_source_key_uidx on public.hatsune_news(source_key) where source_key is not null;

create table if not exists public.bs_daily_result_digests (
  id bigint generated by default as identity primary key,
  race_date date not null unique,
  status text not null default 'complete',
  race_count integer not null default 0,
  venue_count integer not null default 0,
  manshu_count integer not null default 0,
  max_payout integer,
  manshu jsonb not null default '[]'::jsonb,
  incidents jsonb not null default '[]'::jsonb,
  featured_races jsonb not null default '[]'::jsonb,
  data_lab jsonb not null default '{}'::jsonb,
  article_title text,
  article_body text,
  x_post_text text,
  source_url text,
  news_id bigint references public.hatsune_news(id) on delete set null,
  generated_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists bs_daily_result_digests_race_date_idx on public.bs_daily_result_digests(race_date desc);