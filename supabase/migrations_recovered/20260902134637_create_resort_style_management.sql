drop policy if exists "resort admins read own membership" on public.resort_admins;
create policy "resort admins read own membership"
on public.resort_admins for select
to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "public read active resort stores" on public.resort_stores;
create policy "public read active resort stores"
on public.resort_stores for select
to anon, authenticated
using (is_active or exists (
  select 1 from public.resort_admins a where a.user_id = (select auth.uid())
));

drop policy if exists "resort admins manage stores" on public.resort_stores;
create policy "resort admins manage stores"
on public.resort_stores for all
to authenticated
using (exists (select 1 from public.resort_admins a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.resort_admins a where a.user_id = (select auth.uid())));

