create table if not exists public.bsc_official_predictions (
  id bigint generated by default as identity primary key,
  race_date date not null,
  course_code smallint not null check (course_code between 1 and 24),
  race_no smallint not null check (race_no between 1 and 12),
  character_code text not null check (character_code in ('ichika','hatsune','kiina')),
  timing text not null check (timing in ('previous_day','after_exhibition')),
  ranking_type text,
  rank_no integer,
  source_table text not null default 'manual',
  source_id text not null,
  prediction_label text,
  tickets jsonb not null default '[]'::jsonb check (jsonb_typeof(tickets) = 'array'),
  unit_stake integer not null default 100 check (unit_stake > 0),
  investment integer generated always as (jsonb_array_length(tickets) * unit_stake) stored,
  snapshot jsonb not null default '{}'::jsonb,
  published_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (character_code, timing, source_table, source_id)
);

create index if not exists idx_bsc_official_predictions_race
  on public.bsc_official_predictions (race_date, course_code, race_no);
create index if not exists idx_bsc_official_predictions_character_date
  on public.bsc_official_predictions (character_code, race_date, timing);

create table if not exists public.bsc_official_results (
  prediction_id bigint primary key references public.bsc_official_predictions(id) on delete cascade,
  result_combination text not null,
  trifecta_payout integer not null default 0,
  is_hit boolean not null default false,
  hit_ticket text,
  payout integer not null default 0,
  profit integer not null default 0,
  settled_at timestamptz not null default now(),
  settlement_source text not null default 'bs_race_results',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.bsc_settle_official_predictions(target_date date default null)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  affected integer := 0;
begin
  insert into public.bsc_official_results (
    prediction_id,
    result_combination,
    trifecta_payout,
    is_hit,
    hit_ticket,
    payout,
    profit,
    settled_at,
    settlement_source,
    updated_at
  )
  select
    p.id,
    coalesce(nullif(r.winning_trifecta, ''), nullif(r.trifecta_result, '')) as result_combination,
    coalesce(r.trifecta_payout, 0) as trifecta_payout,
    p.tickets ? coalesce(nullif(r.winning_trifecta, ''), nullif(r.trifecta_result, '')) as is_hit,
    case
      when p.tickets ? coalesce(nullif(r.winning_trifecta, ''), nullif(r.trifecta_result, ''))
        then coalesce(nullif(r.winning_trifecta, ''), nullif(r.trifecta_result, ''))
      else null
    end as hit_ticket,
    case
      when p.tickets ? coalesce(nullif(r.winning_trifecta, ''), nullif(r.trifecta_result, ''))
        then round(coalesce(r.trifecta_payout, 0) * p.unit_stake / 100.0)::integer
      else 0
    end as payout,
    case
      when p.tickets ? coalesce(nullif(r.winning_trifecta, ''), nullif(r.trifecta_result, ''))
        then round(coalesce(r.trifecta_payout, 0) * p.unit_stake / 100.0)::integer - p.investment
      else -p.investment
    end as profit,
    now(),
    'bs_race_results',
    now()
  from public.bsc_official_predictions p
  join public.bs_race_results r
    on r.race_date = p.race_date
   and r.course_code = p.course_code
   and r.race_no = p.race_no
  where (target_date is null or p.race_date = target_date)
    and coalesce(nullif(r.winning_trifecta, ''), nullif(r.trifecta_result, '')) is not null
  on conflict (prediction_id) do update set
    result_combination = excluded.result_combination,
    trifecta_payout = excluded.trifecta_payout,
    is_hit = excluded.is_hit,
    hit_ticket = excluded.hit_ticket,
    payout = excluded.payout,
    profit = excluded.profit,
    settled_at = excluded.settled_at,
    settlement_source = excluded.settlement_source,
    updated_at = excluded.updated_at;

  get diagnostics affected = row_count;
  return affected;
end;
$$;

create or replace view public.v_bsc_official_performance as
select
  p.id as prediction_id,
  p.race_date,
  p.course_code,
  p.race_no,
  p.character_code,
  p.timing,
  p.ranking_type,
  p.rank_no,
  p.prediction_label,
  p.tickets,
  p.unit_stake,
  p.investment,
  p.published_at,
  r.result_combination,
  r.trifecta_payout,
  r.is_hit,
  r.hit_ticket,
  r.payout,
  r.profit,
  r.settled_at
from public.bsc_official_predictions p
join public.bsc_official_results r on r.prediction_id = p.id;

create or replace view public.v_bsc_official_monthly_stats as
select
  date_trunc('month', p.race_date)::date as month,
  p.character_code,
  p.timing,
  count(*)::bigint as prediction_count,
  count(*) filter (where r.is_hit)::bigint as hit_count,
  round((100.0 * count(*) filter (where r.is_hit) / nullif(count(*), 0))::numeric, 2) as hit_rate,
  sum(p.investment)::bigint as investment,
  sum(r.payout)::bigint as payout,
  sum(r.profit)::bigint as profit,
  round((100.0 * sum(r.payout) / nullif(sum(p.investment), 0))::numeric, 2) as recovery_rate,
  max(r.payout)::integer as max_payout,
  max(r.settled_at) as latest_settled_at
from public.bsc_official_predictions p
join public.bsc_official_results r on r.prediction_id = p.id
group by 1, p.character_code, p.timing;

alter table public.bsc_official_predictions enable row level security;
alter table public.bsc_official_results enable row level security;

revoke all on function public.bsc_settle_official_predictions(date) from public;
grant execute on function public.bsc_settle_official_predictions(date) to service_role;
grant select on public.v_bsc_official_performance to anon, authenticated;
grant select on public.v_bsc_official_monthly_stats to anon, authenticated;