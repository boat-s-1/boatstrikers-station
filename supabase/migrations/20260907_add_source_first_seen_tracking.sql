create or replace function public.bs_track_ai_first_seen()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_seen_at timestamptz;
begin
  v_seen_at := coalesce(new.generated_at, new.predicted_at, new.created_at);
  if v_seen_at is not null and coalesce(new.timing,'') ilike '%live%' then
    perform public.bs_record_first_seen(
      new.race_date,
      new.course_code,
      new.race_no,
      'ai',
      coalesce(nullif(new.character_code,''), 'AI'),
      v_seen_at
    );
  end if;
  return new;
end;
$$;

drop trigger if exists trg_bs_track_ai_first_seen on public.bs_ai_predictions;
create trigger trg_bs_track_ai_first_seen
after insert or update on public.bs_ai_predictions
for each row execute function public.bs_track_ai_first_seen();

create or replace view public.v_bs_source_speed_comparison
with (security_invoker = true)
as
with x as (
  select
    race_date,
    course_code,
    race_no,
    min(first_seen_at) filter (where data_kind='exhibition' and source='PC-KYOTEI') as pc_exhibition_at,
    min(first_seen_at) filter (where data_kind='exhibition' and source<>'PC-KYOTEI') as api_exhibition_at,
    min(first_seen_at) filter (where data_kind='result' and source='PC-KYOTEI') as pc_result_at,
    min(first_seen_at) filter (where data_kind='result' and source<>'PC-KYOTEI') as api_result_at,
    min(first_seen_at) filter (where data_kind='ai') as live_ai_at
  from public.bs_source_first_seen
  group by race_date, course_code, race_no
)
select
  *,
  extract(epoch from (pc_exhibition_at - api_exhibition_at))::numeric(12,3) as exhibition_pc_minus_api_seconds,
  case
    when api_exhibition_at is null or pc_exhibition_at is null then null
    when api_exhibition_at < pc_exhibition_at then 'API'
    when pc_exhibition_at < api_exhibition_at then 'PC-KYOTEI'
    else 'TIE'
  end as exhibition_winner,
  extract(epoch from (live_ai_at - least(api_exhibition_at, pc_exhibition_at)))::numeric(12,3) as exhibition_to_ai_seconds,
  extract(epoch from (pc_result_at - api_result_at))::numeric(12,3) as result_pc_minus_api_seconds,
  case
    when api_result_at is null or pc_result_at is null then null
    when api_result_at < pc_result_at then 'API'
    when pc_result_at < api_result_at then 'PC-KYOTEI'
    else 'TIE'
  end as result_winner
from x;
