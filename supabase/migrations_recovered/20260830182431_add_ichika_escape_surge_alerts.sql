create table if not exists public.bs_ichika_escape_surge_alerts (
  id bigint generated by default as identity primary key,
  race_date date not null,
  course_code smallint not null check (course_code between 1 and 24),
  course_name text,
  race_no smallint not null check (race_no between 1 and 12),
  closing_time time,
  exhibition_time numeric,
  lap_time numeric,
  recommended_second_boat smallint check (recommended_second_boat between 2 and 6),
  recommended_second_national_win_rate numeric,
  baseline_win_rate numeric not null default 51.70,
  signal_win_rate numeric not null default 66.36,
  uplift_points numeric not null default 14.66,
  detected_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (race_date, course_code, race_no)
);

alter table public.bs_ichika_escape_surge_alerts enable row level security;

create index if not exists bs_ichika_escape_surge_alerts_race_date_idx
  on public.bs_ichika_escape_surge_alerts (race_date desc, closing_time asc);

create or replace function public.evaluate_ichika_escape_surge_alerts()
returns integer
language plpgsql
security invoker
set search_path = public
as $$
declare
  inserted_count integer := 0;
begin
  with today_entries as (
    select
      e.race_date,
      e.course_code,
      e.race_no,
      e.boat_no,
      coalesce(e.official_exhibition_time, e.exhibition_time) as exhibition_time,
      coalesce(e.official_lap, e.lap_time) as lap_time,
      e.national_win_rate,
      e.local_win_rate
    from public.bs_race_entries e
    where e.race_date = (now() at time zone 'Asia/Tokyo')::date
  ),
  race_ready as (
    select
      race_date,
      course_code,
      race_no,
      count(*) filter (where exhibition_time is not null and lap_time is not null) as complete_rows,
      min(exhibition_time) as best_exhibition,
      min(lap_time) as best_lap
    from today_entries
    group by race_date, course_code, race_no
    having count(*) filter (where exhibition_time is not null and lap_time is not null) = 6
  ),
  qualifying as (
    select
      t.race_date,
      t.course_code,
      t.race_no,
      t.exhibition_time,
      t.lap_time
    from today_entries t
    join race_ready r
      using (race_date, course_code, race_no)
    where t.boat_no = 1
      and t.exhibition_time = r.best_exhibition
      and t.lap_time = r.best_lap
  ),
  recommended as (
    select distinct on (t.race_date, t.course_code, t.race_no)
      t.race_date,
      t.course_code,
      t.race_no,
      t.boat_no as recommended_second_boat,
      t.national_win_rate as recommended_second_national_win_rate
    from today_entries t
    join qualifying q using (race_date, course_code, race_no)
    where t.boat_no between 2 and 6
    order by
      t.race_date,
      t.course_code,
      t.race_no,
      t.national_win_rate desc nulls last,
      t.local_win_rate desc nulls last,
      t.boat_no asc
  ),
  inserted as (
    insert into public.bs_ichika_escape_surge_alerts (
      race_date,
      course_code,
      course_name,
      race_no,
      closing_time,
      exhibition_time,
      lap_time,
      recommended_second_boat,
      recommended_second_national_win_rate
    )
    select
      q.race_date,
      q.course_code,
      ev.course_name,
      q.race_no,
      coalesce(ev.closing_time, ev.deadline_time),
      q.exhibition_time,
      q.lap_time,
      rec.recommended_second_boat,
      rec.recommended_second_national_win_rate
    from qualifying q
    left join public.bs_race_events ev
      on ev.race_date = q.race_date
     and ev.course_code = q.course_code
     and ev.race_no = q.race_no
    left join recommended rec
      using (race_date, course_code, race_no)
    on conflict (race_date, course_code, race_no) do nothing
    returning 1
  )
  select count(*) into inserted_count from inserted;

  return inserted_count;
end;
$$;
