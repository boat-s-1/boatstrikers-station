-- It intentionally creates no production data and grants no anon/authenticated privileges.
-- Production's identity sequence currently grants rwU to anon/authenticated as well;
-- this disposable fixture intentionally tightens that sequence ACL. It does not
-- claim byte-for-byte privilege parity, only the service_role insert/update path.
BEGIN;
CREATE TABLE public.hatsune_news_cron_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_name text NOT NULL CHECK (job_name IN ('pipeline', 'ai')),
  status text NOT NULL CHECK (status IN ('running', 'success', 'error', 'partial')),
  started_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  duration_ms integer,
  collected_count integer NOT NULL DEFAULT 0,
  inserted_count integer NOT NULL DEFAULT 0,
  skipped_count integer NOT NULL DEFAULT 0,
  ai_processed_count integer NOT NULL DEFAULT 0,
  ai_generated_count integer NOT NULL DEFAULT 0,
  error_count integer NOT NULL DEFAULT 0,
  error_message text,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX hatsune_news_cron_runs_started_idx ON public.hatsune_news_cron_runs(started_at DESC);
ALTER TABLE public.hatsune_news_cron_runs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.hatsune_news_cron_runs FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.hatsune_news_cron_runs TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.hatsune_news_cron_runs_id_seq TO service_role;
COMMIT;

